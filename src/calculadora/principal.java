    private void displayKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_displayKeyPressed
        // TODO add your handling code here:
        int tecla = evt.getKeyCode();
        char c = evt.getKeyChar();

        if(c == '+'){
            numero = Double.parseDouble(display.getText());
            operacao = 1;
            historico.setText(display.getText() + " + ");
            display.setText("");
        } else if(c == '-'){
            numero = Double.parseDouble(display.getText());
            operacao = 2;
            historico.setText(display.getText() + " - ");
            display.setText("");
        } else if(c == '*'){
            numero = Double.parseDouble(display.getText());
            operacao = 3;
            historico.setText(display.getText() + " * ");
            display.setText("");
        } else if(c == '/'){
            numero = Double.parseDouble(display.getText());
            operacao = 4;
            historico.setText(display.getText() + " / ");
            display.setText("");
        } else if(tecla == KeyEvent.VK_ENTER){
            switch(operacao){
                case 1:
                double r = numero + Double.parseDouble(display.getText());
                historico.setText("" + historico.getText() + display.getText() +  " = ");
                display.setText("" + r);
                break;
            

            case 2:
                r = numero - Double.parseDouble(display.getText());
                historico.setText("" + historico.getText() + display.getText() +  " = ");
                display.setText("" + r);
                break;
            

            case 3:
                r = numero * Double.parseDouble(display.getText());
                historico.setText("" + historico.getText() + display.getText() +  " = ");
                display.setText("" + r);
                break;
            

            case 4:

                if(Double.parseDouble(display.getText()) != 0){

                    r = numero / Double.parseDouble(display.getText());
                    historico.setText("" + historico.getText() + display.getText() +  " = ");
                    display.setText("" + r);

                } else {

                    display.setText("Não é possível dividir por 0");
                }
                break;
            
            }
        }  
    }//GEN-LAST:event_displayKeyPressed

