    private void igualMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_igualMouseClicked
        // TODO add your handling code here:
        if(operacao==1){
            double resultado = numero + Double.parseDouble(display.getText());
            historico.setText("" + historico.getText() + display.getText() +  " = ");
            display.setText("" + resultado);
        } else if (operacao==2){
            double resultado = numero - Double.parseDouble(display.getText());
            historico.setText("" + historico.getText() + display.getText() +  " = ");
            display.setText("" + resultado);
        } else if (operacao==3){
            double resultado = numero * Double.parseDouble(display.getText());
            historico.setText("" + historico.getText() + display.getText() +  " = ");
            display.setText("" + resultado);
        } else if(operacao==4){
            if(Double.parseDouble(display.getText()) != 0){
                double resultado = numero / Double.parseDouble(display.getText());
                historico.setText("" + historico.getText() + display.getText() +  " = ");
                display.setText("" + resultado);
            } else {
                display.setText("Não é possível dividir por 0");
            }
        } else if (operacao==5){
            double resultado = Math.pow(numero,Double.parseDouble(display.getText()));
            historico.setText("" + historico.getText() + display.getText() +  " = ");
            display.setText("" + resultado);
        }
    }//GEN-LAST:event_igualMouseClicked

